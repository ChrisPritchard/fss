        | None -> ()

        for (n, _, e, _) in topValueList do
            line (sprintf "v_%s = %s;" n (value e))
        match prog.Main with
        | Some body -> emitStmt body
        | None -> ()
        line "return 0;"
        level <- 0
        line "}"

    // C interop: `#include "..."` directives and `extern` declarations.
    // Each extern becomes a static wrapper around the real C function. We do
    // not re-declare the foreign prototype ourselves: that would clash with
    // the header the user includes (e.g. `strcmp` is `const char*`), and the
    // wrapper lets the C compiler apply the usual implicit conversions.
    let externDeclSb2 = StringBuilder()
    for (n, ps, r) in prog.Externs do
        let args =
            ps
            |> List.mapi (fun i (_, t) ->
                let (decl, isCb) = externParamType n t
                if isCb then decl.Replace("(*)", "(* a" + string i + ")")
                else decl + " a" + string i)
            |> String.concat ", "
        let argNames = ps |> List.mapi (fun i _ -> "a" + string i) |> String.concat ", "
        let body =
            if Typer.resolveTy r = UnitTy then sprintf "{ %s(%s); }" n argNames
            else sprintf "{ return %s(%s); }" n argNames
        externDeclSb2.AppendLine(sprintf "static %s fs_ext_%s(%s) %s" (ctypeRet r) n args body) |> ignore

    let final = StringBuilder()
    final.Append(preamble).AppendLine() |> ignore
    for inc in prog.Includes do
        if inc.StartsWith("<") then final.AppendLine(sprintf "#include %s" inc) |> ignore
