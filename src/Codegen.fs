            match Map.tryFind n topFuns with
            | Some (ptys, rt) ->
                let args =
                    ptys |> List.mapi (fun i t -> exportCType n t + " a" + string i) |> String.concat ", "
                let argNames = ptys |> List.mapi (fun i _ -> "a" + string i) |> String.concat ", "
                let retC = exportCType n rt
                // cstring params/returns need no conversion; everything else
                // is already the same C type.
                let call = "v_" + n + "(" + argNames + ")"
                if Typer.resolveTy rt = UnitTy then line (sprintf "%s %s(%s) { %s; }" retC cname args call)
                else line (sprintf "%s %s(%s) { return %s; }" retC cname args call)
            | None -> failwith ("[<Export>] on non-function '" + n + "'")
    else
        match prog.MainArg with
        | Some _ -> line "int main(int argc, char** argv) {"
        | None -> line "int main(void) {"
        level <- 1

        line "{ void* fs_stack_anchor; fs_gc_init(&fs_stack_anchor); }"
        for (n, t, _, _) in topValueList do
            line (sprintf "fs_add_root((void*)&v_%s, sizeof(%s));" n (ctypeArg (Typer.resolveTy t)))

        match prog.MainArg with
        | Some argName ->
            let ln = listName StringTy
            scope <- Map.add argName { CName = "v_" + argName; Ty = TNamed("list", [ StringTy ]); Mutable = false } scope
