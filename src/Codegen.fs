        "    fsstring_t r; r.len = (int32_t)n; r.data = (char*)fs_alloc((size_t)n + 1);\n" +
        "    memcpy(r.data, buf, (size_t)n); r.data[n] = 0; return r;\n" +
        "}\n" +
